using Animora.Domain.Events;
using Animora.Domain.Primitives;
using Animora.Domain.Results;
using Animora.Domain.Time;

namespace Animora.Domain.Scheduling;

/// <summary>Lifecycle state of an appointment.</summary>
public enum AppointmentState
{
    /// <summary>Booked, not yet confirmed with the owner.</summary>
    Scheduled = 0,

    /// <summary>Confirmed with the owner.</summary>
    Confirmed = 1,

    /// <summary>The patient has arrived and been checked in at reception.</summary>
    CheckedIn = 2,

    /// <summary>The encounter has started; a visit exists.</summary>
    InVisit = 3,

    /// <summary>The encounter finished. Terminal.</summary>
    Completed = 4,

    /// <summary>The patient did not arrive. Terminal.</summary>
    NoShow = 5,

    /// <summary>The appointment was cancelled. Terminal.</summary>
    Cancelled = 6,
}

/// <summary>How the appointment came to be booked.</summary>
public enum AppointmentSource
{
    /// <summary>Booked over the phone.</summary>
    Phone = 0,

    /// <summary>Booked at the desk on arrival.</summary>
    WalkIn = 1,

    /// <summary>Booked through an online channel.</summary>
    Online = 2,

    /// <summary>A follow-up scheduled from an earlier encounter.</summary>
    Followup = 3,

    /// <summary>A recall generated by a reminder.</summary>
    Recall = 4,
}

/// <summary>
/// The appointment aggregate root: one scheduled slot for one patient, from booking to completion.
/// </summary>
/// <remarks>
/// <para>
/// The state machine below is the <b>only</b> authority over what may change and when
/// (CONVENTIONS.md §6 item 9 — the domain decides, a version mismatch never does):
/// </para>
/// <code>
/// Scheduled  -> Confirmed | CheckedIn | Cancelled | NoShow
/// Confirmed  -> CheckedIn | Cancelled | NoShow
/// CheckedIn  -> InVisit   | Cancelled | NoShow
/// InVisit    -> Completed | Cancelled
/// Completed / NoShow / Cancelled -> (terminal)
/// </code>
/// <para>
/// The slot-conflict invariant is not enforced here: it depends on the other appointments in the
/// tenant's calendar, which only the Application layer can supply. <see cref="SlotConflictPolicy"/>
/// is the authoritative rule and is called by the caller before <see cref="Book"/> (ARCHITECTURE.md
/// §8.5). This aggregate owns only the invariants it can see: the duration rule and the state
/// machine. Every mutator returns <see cref="Result"/> — an out-of-order click is expected user
/// behaviour, not a defect.
/// </para>
/// </remarks>
public sealed class Appointment : AggregateRoot
{
    /// <summary>Minimum slot length in minutes.</summary>
    public const int MinDurationMinutes = 5;

    /// <summary>Maximum slot length in minutes.</summary>
    public const int MaxDurationMinutes = 480;

    /// <summary>Slot lengths must be a multiple of this many minutes.</summary>
    public const int DurationStepMinutes = 5;

    /// <summary>EF Core materialization constructor. Not for business code.</summary>
    private Appointment()
    {
    }

    /// <summary>The patient scheduled.</summary>
    public string PetId { get; private set; } = string.Empty;

    /// <summary>The patient's owner, denormalized so reception never needs a second read.</summary>
    public string OwnerId { get; private set; } = string.Empty;

    /// <summary>The assigned doctor, or <see langword="null"/> when triaged at reception.</summary>
    public string? DoctorUserId { get; private set; }

    /// <summary>The appointment type code, e.g. <c>CHECKUP</c> (see <see cref="AppointmentTypeCatalog"/>).</summary>
    public string AppointmentTypeCode { get; private set; } = string.Empty;

    /// <summary>Slot start, UTC.</summary>
    public DateTimeOffset StartUtc { get; private set; }

    /// <summary>Slot length in minutes.</summary>
    public int DurationMinutes { get; private set; }

    /// <summary>Current lifecycle state.</summary>
    public AppointmentState State { get; private set; } = AppointmentState.Scheduled;

    /// <summary>How the appointment was booked.</summary>
    public AppointmentSource Source { get; private set; }

    /// <summary>Free-form reception note.</summary>
    public string? Note { get; private set; }

    /// <summary>The visit this appointment turned into (A04); set by <see cref="StartVisit"/>.</summary>
    public string? VisitId { get; private set; }

    /// <summary>Why the appointment was cancelled; kept for the audit trail.</summary>
    public string? CancelReason { get; private set; }

    /// <summary>When the patient was checked in, UTC; <see langword="null"/> until then.</summary>
    public DateTimeOffset? CheckedInUtc { get; private set; }

    /// <summary>The user who booked the appointment.</summary>
    public string CreatedByUserId { get; private set; } = string.Empty;

    /// <summary>How many times the slot has been moved.</summary>
    public int RescheduleCount { get; private set; }

    /// <summary>Exclusive slot end: <c>StartUtc + DurationMinutes</c>.</summary>
    public DateTimeOffset EndUtc => StartUtc.AddMinutes(DurationMinutes);

    /// <summary>This appointment's slot as a value object.</summary>
    public AppointmentSlot Slot => new(StartUtc, DurationMinutes);

    /// <summary>
    /// Books an appointment in <see cref="AppointmentState.Scheduled"/>. The caller must have already
    /// cleared the slot with <see cref="SlotConflictPolicy"/> — this method does not re-check it.
    /// Raises <see cref="AppointmentBookedEvent"/>.
    /// </summary>
    public static Result<Appointment> Book(
        string tenantId,
        string petId,
        string ownerId,
        string appointmentTypeCode,
        DateTimeOffset startUtc,
        int durationMinutes,
        AppointmentSource source,
        string createdByUserId,
        IClock clock,
        string? doctorUserId = null,
        string? note = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(tenantId);
        ArgumentException.ThrowIfNullOrWhiteSpace(petId);
        ArgumentException.ThrowIfNullOrWhiteSpace(ownerId);
        ArgumentException.ThrowIfNullOrWhiteSpace(appointmentTypeCode);
        ArgumentException.ThrowIfNullOrWhiteSpace(createdByUserId);
        ArgumentNullException.ThrowIfNull(clock);

        var durationCheck = EnsureDurationValid(durationMinutes);
        if (durationCheck.IsFailure)
        {
            return Result<Appointment>.Fail(durationCheck.Error, durationCheck.Detail);
        }

        var now = clock.UtcNow;
        var appointment = new Appointment
        {
            Id = IdGenerator.NewId(now),
            TenantId = tenantId,
            PetId = petId,
            OwnerId = ownerId,
            DoctorUserId = string.IsNullOrWhiteSpace(doctorUserId) ? null : doctorUserId,
            AppointmentTypeCode = appointmentTypeCode,
            StartUtc = startUtc,
            DurationMinutes = durationMinutes,
            State = AppointmentState.Scheduled,
            Source = source,
            Note = Clean(note),
            CreatedByUserId = createdByUserId,
        };

        appointment.Raise(new AppointmentBookedEvent(
            IdGenerator.NewId(now), tenantId, now, appointment.Id, petId, ownerId,
            appointment.DoctorUserId, startUtc, durationMinutes));
        return appointment;
    }

    /// <summary>Confirms the appointment with the owner.</summary>
    public Result Confirm() => Transition(AppointmentState.Confirmed);

    /// <summary>Checks the patient in on arrival, stamping <see cref="CheckedInUtc"/>.</summary>
    public Result CheckIn(IClock clock)
    {
        ArgumentNullException.ThrowIfNull(clock);

        var moved = Transition(AppointmentState.CheckedIn);
        if (moved.IsFailure)
        {
            return moved;
        }

        CheckedInUtc = clock.UtcNow;
        return Result.Ok();
    }

    /// <summary>
    /// Opens the encounter, linking the visit. Only legal from <see cref="AppointmentState.CheckedIn"/>:
    /// a visit cannot start for a patient who has not arrived.
    /// </summary>
    public Result StartVisit(string visitId)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(visitId);

        var moved = Transition(AppointmentState.InVisit);
        if (moved.IsFailure)
        {
            return moved;
        }

        VisitId = visitId;
        return Result.Ok();
    }

    /// <summary>Marks the encounter finished.</summary>
    public Result Complete() => Transition(AppointmentState.Completed);

    /// <summary>Records that the patient did not arrive.</summary>
    public Result MarkNoShow(IClock clock)
    {
        ArgumentNullException.ThrowIfNull(clock);
        return Transition(AppointmentState.NoShow);
    }

    /// <summary>Cancels the appointment. Raises <see cref="AppointmentCancelledEvent"/>.</summary>
    public Result Cancel(string reason, IClock clock)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(reason);
        ArgumentNullException.ThrowIfNull(clock);

        var moved = Transition(AppointmentState.Cancelled);
        if (moved.IsFailure)
        {
            return moved;
        }

        CancelReason = reason.Trim();
        var now = clock.UtcNow;
        Raise(new AppointmentCancelledEvent(IdGenerator.NewId(now), TenantId, now, Id, CancelReason));
        return Result.Ok();
    }

    /// <summary>
    /// Moves the appointment to a new slot and increments <see cref="RescheduleCount"/>. Forbidden
    /// once <see cref="State"/> is <see cref="AppointmentState.InVisit"/> or later — the encounter has
    /// begun (<c>APPOINTMENT_NOT_MOVABLE</c>). The caller must re-clear the new slot with
    /// <see cref="SlotConflictPolicy"/> first. Raises <see cref="AppointmentMovedEvent"/>.
    /// </summary>
    public Result Move(DateTimeOffset newStartUtc, int newDurationMinutes, IClock clock)
    {
        ArgumentNullException.ThrowIfNull(clock);

        if (State >= AppointmentState.InVisit)
        {
            return Result.Fail(
                ErrorCodes.AppointmentNotMovable,
                $"Appointment '{Id}' is {State}; its slot is fixed.");
        }

        var durationCheck = EnsureDurationValid(newDurationMinutes);
        if (durationCheck.IsFailure)
        {
            return durationCheck;
        }

        var oldStart = StartUtc;
        StartUtc = newStartUtc;
        DurationMinutes = newDurationMinutes;
        RescheduleCount++;

        var now = clock.UtcNow;
        Raise(new AppointmentMovedEvent(
            IdGenerator.NewId(now), TenantId, now, Id, oldStart, newStartUtc, newDurationMinutes));
        return Result.Ok();
    }

    /// <summary><see langword="true"/> when the tabled machine allows <paramref name="from"/> → <paramref name="to"/>.</summary>
    public static bool IsTransitionAllowed(AppointmentState from, AppointmentState to) => (from, to) switch
    {
        (AppointmentState.Scheduled, AppointmentState.Confirmed) => true,
        (AppointmentState.Scheduled, AppointmentState.CheckedIn) => true,
        (AppointmentState.Scheduled, AppointmentState.Cancelled) => true,
        (AppointmentState.Scheduled, AppointmentState.NoShow) => true,
        (AppointmentState.Confirmed, AppointmentState.CheckedIn) => true,
        (AppointmentState.Confirmed, AppointmentState.Cancelled) => true,
        (AppointmentState.Confirmed, AppointmentState.NoShow) => true,
        (AppointmentState.CheckedIn, AppointmentState.InVisit) => true,
        (AppointmentState.CheckedIn, AppointmentState.Cancelled) => true,
        (AppointmentState.CheckedIn, AppointmentState.NoShow) => true,
        (AppointmentState.InVisit, AppointmentState.Completed) => true,
        (AppointmentState.InVisit, AppointmentState.Cancelled) => true,
        _ => false,
    };

    /// <summary>The single gate every state change goes through.</summary>
    private Result Transition(AppointmentState target)
    {
        if (!IsTransitionAllowed(State, target))
        {
            return Result.Fail(
                ErrorCodes.AppointmentInvalidTransition,
                $"Appointment '{Id}' cannot move {State} -> {target}.");
        }

        State = target;
        return Result.Ok();
    }

    private static Result EnsureDurationValid(int durationMinutes) =>
        durationMinutes is >= MinDurationMinutes and <= MaxDurationMinutes
            && durationMinutes % DurationStepMinutes == 0
                ? Result.Ok()
                : Result.Fail(
                    ErrorCodes.AppointmentDurationInvalid,
                    $"Duration {durationMinutes} must be in [{MinDurationMinutes}, {MaxDurationMinutes}] and a multiple of {DurationStepMinutes}.");

    private static string? Clean(string? value) =>
        string.IsNullOrWhiteSpace(value) ? null : value.Trim();
}

using System.Linq.Expressions;
using Animora.Domain.Primitives;
using Animora.Persistence.PostgreSql.Concurrency;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace Animora.Persistence.PostgreSql.Conventions;

/// <summary>
/// Single source of truth for the server-side shape shared by every tenant/synced table
/// (CONVENTIONS §5): named tenant + soft-delete query filters, <c>uuid</c> trigger-owned
/// <c>Version</c> concurrency token, <c>timestamptz(6)</c> UTC timestamps, integer enums and
/// tenant-first indexes.
/// </summary>
public static class ServerModelConventions
{
    /// <summary>Named query filter scoping rows to the tenant in context.</summary>
    public const string TenantFilterName = "Tenant";

    /// <summary>Named query filter hiding soft-deleted rows.</summary>
    public const string SoftDeleteFilterName = "SoftDelete";

    private static readonly ValueConverter<DateTimeOffset, DateTimeOffset> UtcConverter = new(
        v => v.ToUniversalTime(),
        v => v.ToUniversalTime());

    /// <summary>
    /// Applies tenancy, soft-delete, version and column conventions to every
    /// <see cref="SyncableEntity"/> root type in the model.
    /// </summary>
    /// <param name="modelBuilder">The model under construction.</param>
    /// <param name="tenantAccessor">
    /// An expression reading the current tenant from the owning <see cref="DbContext"/>
    /// (e.g. <c>() =&gt; CurrentTenantId</c>). It must stay an expression rooted at the
    /// context instance: EF re-binds that reference per query, so one cached model serves
    /// many contexts/tenants. The accessor throws when no tenant is bound.
    /// </param>
    public static void ApplyTenancy(ModelBuilder modelBuilder, Expression<Func<string>> tenantAccessor)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);
        ArgumentNullException.ThrowIfNull(tenantAccessor);

        foreach (IMutableEntityType entityType in modelBuilder.Model.GetEntityTypes().ToArray())
        {
            Type clrType = entityType.ClrType;
            if (!typeof(SyncableEntity).IsAssignableFrom(clrType))
            {
                continue;
            }

            ConfigureColumns(modelBuilder.Entity(clrType));

            // Query filters may only be declared on the root of a hierarchy.
            if (entityType.BaseType is null)
            {
                ConfigureFilters(modelBuilder.Entity(clrType), clrType, tenantAccessor);
            }
        }
    }

    /// <summary>
    /// Adds an index whose first column is <c>TenantId</c>, followed by <paramref name="columns"/>,
    /// named <c>IX_&lt;Table&gt;_TenantId_&lt;Cols&gt;</c>.
    /// </summary>
    public static IndexBuilder TenantIndex(EntityTypeBuilder entity, params string[] columns)
    {
        ArgumentNullException.ThrowIfNull(entity);
        ArgumentNullException.ThrowIfNull(columns);

        string table = entity.Metadata.GetTableName() ?? entity.Metadata.ClrType.Name;
        string[] all = [nameof(SyncableEntity.TenantId), .. columns];
        return entity.HasIndex(all).HasDatabaseName($"IX_{table}_{string.Join('_', all)}");
    }

    private static void ConfigureColumns(EntityTypeBuilder entity)
    {
        entity.Property(nameof(SyncableEntity.Id)).HasColumnType("character varying(26)").HasMaxLength(26);
        entity.Property(nameof(SyncableEntity.TenantId)).HasColumnType("character varying(26)").HasMaxLength(26).IsRequired();

        entity.Property(nameof(SyncableEntity.UpdatedAt))
            .HasConversion(UtcConverter)
            .HasColumnType("timestamp with time zone")
            .HasPrecision(6);

        entity.Property(nameof(SyncableEntity.Deleted)).HasColumnType("boolean").HasDefaultValue(false).IsRequired();

        // Server-owned opaque version: uuid NOT NULL, regenerated by the trigger. Never xmin/rowversion.
        entity.Property(nameof(SyncableEntity.Version))
            .HasColumnName("Version")
            .HasColumnType("uuid")
            .HasConversion<StringGuidConverter>()
            .HasDefaultValueSql("gen_random_uuid()")
            .ValueGeneratedOnAddOrUpdate()
            .IsConcurrencyToken();

        foreach (IMutableProperty property in entity.Metadata.GetProperties())
        {
            Type type = Nullable.GetUnderlyingType(property.ClrType) ?? property.ClrType;
            if (type.IsEnum && property.GetValueConverter() is null)
            {
                entity.Property(property.Name).HasConversion(typeof(int)).HasColumnType("integer");
            }
        }
    }

    private static void ConfigureFilters(EntityTypeBuilder entity, Type clrType, Expression<Func<string>> tenantAccessor)
    {
        ParameterExpression e = Expression.Parameter(clrType, "e");

        // e => e.TenantId == <accessor body>   (accessor body stays rooted at the DbContext instance)
        LambdaExpression tenant = Expression.Lambda(
            Expression.Equal(
                Expression.Property(e, nameof(SyncableEntity.TenantId)),
                tenantAccessor.Body),
            e);

        // e => !e.Deleted
        LambdaExpression softDelete = Expression.Lambda(
            Expression.Not(Expression.Property(e, nameof(SyncableEntity.Deleted))),
            e);

        entity.HasQueryFilter(TenantFilterName, tenant);
        entity.HasQueryFilter(SoftDeleteFilterName, softDelete);
    }
}
